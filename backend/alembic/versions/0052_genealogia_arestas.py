def _trgm() -> bool:
    conn = op.get_bind()
    conn.execute(text("SAVEPOINT sigpmf_trgm"))
    try:
        conn.execute(text("CREATE EXTENSION IF NOT EXISTS pg_trgm"))
    except Exception:
        conn.execute(text("ROLLBACK TO SAVEPOINT sigpmf_trgm"))
        return False
    conn.execute(text("RELEASE SAVEPOINT sigpmf_trgm"))
    return True


def _indice_concorrente(sql: str) -> None:
    """Tenta o índice fora da transação. Se o Postgres recusar, cria na transação corrente."""
    ctx = op.get_context()
    try:
        with ctx.autocommit_block():
            op.execute("SET lock_timeout = '120s'")
            op.execute(sql)
    except Exception:
        op.execute(sql.replace(" CONCURRENTLY", "", 1))


